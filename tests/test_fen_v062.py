"""FEN encode/decode tests (core/fen.py).

Built for V0.6.2 (talking to an external Pikafish process) -- see
`docs/v0.6.2.md`. Pays particular attention to the piece-letter
convention (Horse=N, Elephant=B, NOT this project's own internal
`PieceType.value` strings) since that's the single easiest thing to
get subtly wrong here (see fen.py's own module docstring).
"""

import pytest

from alphazetacchess.core.board import Board
from alphazetacchess.core.piece import Color, Piece, PieceType
from alphazetacchess.core.zobrist import Zobrist
from alphazetacchess.core.fen import board_to_fen, board_from_fen


def empty_board():
    board = Board()
    board.board = [[None for _ in range(Board.WIDTH)] for _ in range(Board.HEIGHT)]
    board.history = []
    board.current_player = Color.RED
    board.zobrist_hash = Zobrist.board_hash(board)
    return board


def put(board, piece_type, color, x, y):
    board.board[y][x] = Piece(piece_type, color, x, y)


