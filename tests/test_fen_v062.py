def test_starting_position_matches_the_well_known_standard_fen():
    board = Board()

    fen = board_to_fen(board)

    assert fen == "rnbakabnr/9/1c5c1/p1p1p1p1p/9/9/P1P1P1P1P/1C5C1/9/RNBAKABNR w - - 0 1"


def test_uses_ucci_letters_not_this_projects_own_piecetype_value():
    # PieceType.HORSE.value is "H" and PieceType.ELEPHANT.value is "E"
    # internally -- but Pikafish/UCCI FEN uses N (knight) and B
    # (bishop) respectively. If this test ever starts failing because
    # someone "simplified" fen.py to use piece.type.value directly,
    # that's the bug this test exists to catch.
    board = empty_board()
    put(board, PieceType.HORSE, Color.RED, 0, 0)
    put(board, PieceType.ELEPHANT, Color.BLACK, 8, 9)

    fen = board_to_fen(board)
    placement = fen.split()[0]

    assert "H" not in placement and "h" not in placement
    assert "E" not in placement and "e" not in placement
    assert placement.split("/")[0] == "8b"  # Black elephant, rank 9
    assert placement.split("/")[-1] == "N8"  # Red horse, rank 0


def test_active_color_maps_red_to_w_and_black_to_b():
    board = Board()
    assert board_to_fen(board).split()[1] == "w"

    board.current_player = Color.BLACK
    assert board_to_fen(board).split()[1] == "b"


